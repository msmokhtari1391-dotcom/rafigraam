LANGS = {"fa": FA, "en": EN}
MONTHS_FA = ["فروردین", "اردیبهشت", "خرداد", "تیر", "مرداد", "شهریور",
             "مهر", "آبان", "آذر", "دی", "بهمن", "اسفند"]
MONTHS_EN = ["January", "February", "March", "April", "May", "June", "July",
             "August", "September", "October", "November", "December"]

_lang = "fa"


def set_lang(code: str) -> None:
    global _lang
    _lang = code if code in LANGS else "fa"


def lang() -> str:
    return _lang


def is_en() -> bool:
    return _lang == "en"


def rtl() -> bool:
    return _lang == "fa"


def t(key: str, **kw) -> str:
    table = LANGS.get(_lang, FA)
    s = table.get(key) or FA.get(key) or key
    return s.format(**kw) if kw else s


_FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹"


def num(value) -> str:
    """رقم‌ها رو در حالت فارسی به عددِ فارسی تبدیل می‌کنه."""
    s = str(value)
    if _lang != "fa":
        return s
    return s.translate(str.maketrans("0123456789", _FA_DIGITS))


def months() -> list[str]:
    return MONTHS_FA if _lang == "fa" else MONTHS_EN
